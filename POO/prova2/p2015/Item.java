package prova2.p2015;

public class Item {
    private String nome;
    private int custo;

    public Item(String nome, int custo){
        this.nome = nome;
        this.custo = custo;
    }

    public String getNome(){
        return this.nome;
    }
    public int getCusto(){
        return this.custo;
    }
}



